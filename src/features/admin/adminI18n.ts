export const adminErrorMessage = (reason: unknown, fallback: string, t?: (key: string) => string) => {
  const raw = reason instanceof Error ? reason.message : '';
  if (/failed to fetch|networkerror|load failed/i.test(raw)) return t?.('common.failedToFetch') || fallback;
  return raw || fallback;
};
