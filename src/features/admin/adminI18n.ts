type Lang = keyof typeof dict;
type PathValue<T, P extends string> =
  P extends `${infer K}.${infer R}`
    ? K extends keyof T ? PathValue<T[K], R> : string
    : P extends keyof T ? T[P] : string;

const readPath = (source: any, key: string): any =>
  key.split('.').reduce((current, part) => (current == null ? undefined : current[part]), source);

const interpolate = (value: string, vars?: Record<string, unknown>) =>
  Object.entries(vars || {}).reduce((text, [key, val]) => text.replaceAll(`{{${key}}}`, String(val)), value);

export const useAdminT = () => {
  const { i18n } = useTranslation();
  const lang: Lang = String(i18n.language || '').startsWith('es') ? 'es' : 'en';
  const fallback: Lang = lang === 'es' ? 'en' : 'es';
  const t = useCallback(<K extends string>(key: K, vars?: Record<string, unknown>): PathValue<(typeof dict)[Lang], K> => {
    const value = readPath(dict[lang], key) ?? readPath(dict[fallback], key) ?? key;
    return (typeof value === 'string' ? interpolate(value, vars) : value) as PathValue<(typeof dict)[Lang], K>;
  }, [fallback, lang]);
  return { t, lang };
};

